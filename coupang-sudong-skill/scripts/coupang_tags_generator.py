def generate_coupang_tags(keyword: str, related_queries: list, manu_tags: list, target_count: int = 20) -> list[str]:
    """실시간 크롤링된 연관검색어/태그에서 중복 어근을 배제하고 카테고리 태그 풀과 결합하여 20개 엄선"""
    resolved = resolve_20_category(keyword)
    cat_pool = CATEGORY_TAG_POOLS.get(resolved["matchedCategory"], CATEGORY_TAG_POOLS["패션잡화"])
    
    candidates = related_queries + manu_tags + cat_pool
    unique = []
    seen = set()
    
    for c in candidates:
        t = str(c).strip().replace(" ", "")
        if not t or len(t) < 2 or len(t) > 20:
            continue
        if t not in seen:
            seen.add(t)
            unique.append(c)
            if len(unique) >= target_count:
                break
                
    for def_t in cat_pool:
        if len(unique) >= target_count:
            break
        clean_def = def_t.replace(" ", "")
        if clean_def not in seen:
            seen.add(clean_def)
            unique.append(def_t)
            
    return unique[:target_count]

