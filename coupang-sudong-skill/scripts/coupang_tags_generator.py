def get_dynamic_tags_for_category(category_group: str, main_keyword: str = "", count: int = 20) -> list[str]:
    """카테고리 그룹에 맞는 최적 20개 태그를 동적으로 도출 (키워드 최적화 반영)"""
    pool = CATEGORY_TAG_POOLS.get(category_group, CATEGORY_TAG_POOLS["패션잡화"])
    clean_kw = re.sub(r"\s+", "", main_keyword).strip()
    
    res = []
    seen = set()
    
    # 1. 메인 키워드 파생 태그 우선 결합
    if clean_kw and len(clean_kw) >= 2:
        res.append(clean_kw)
        seen.add(clean_kw)
        
    for tag in pool:
        c_tag = re.sub(r"\s+", "", tag).strip()
        if c_tag and c_tag not in seen:
            seen.add(c_tag)
            res.append(tag)
        if len(res) >= count:
            break
            
    return res[:count]

def get_coupang_tags(main_keyword: str = "상품", category_group: str | None = None) -> list[str]:
    """쿠팡용 20개 태그 반환 (키워드/카테고리 동적 매핑)"""
    if not category_group:
        resolved = resolve_20_category(main_keyword)
        category_group = resolved["matchedCategory"]
    return get_dynamic_tags_for_category(category_group, main_keyword, count=20)

